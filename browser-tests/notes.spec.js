test('failed book searches can be retried and changing the scope discards a pending search', async ({ page }) => {
    await open(page, { text: 'ג א ג', mode: 'aleph-one', url: '/?lang=en' });
    await page.getByRole('button', { name: 'Research', exact: true }).click();
    const view = page.getByRole('region', { name: 'Research', exact: true });
    const scope = view.getByRole('combobox', { name: 'Search scope' });
    await view.getByRole('textbox', { name: 'Operator formula' }).fill('U = W');
    await scope.selectOption('esther');
    await page.route('**/corpus/books/esther.json', route => route.abort(), { times: 1 });
    const find = view.getByRole('button', { name: 'Find matches' });
    await find.click();
    await expect(view.getByRole('alert')).toBeVisible();
    await expect(view.locator('.operator-results')).toHaveCount(0);
    let release;
    const pause = new Promise(resolve => { release = resolve; });
    await page.route('**/corpus/books/esther.json', async route => { await pause; await route.continue(); }, { times: 1 });
    const request = page.waitForRequest('**/corpus/books/esther.json');
    await find.click(); await request;
    await scope.selectOption('passage');
    await find.click();
    await expect(view.getByRole('status')).toContainText('1 of 1 searched');
    release();
    await scope.selectOption('esther'); await find.click();
    await expect(view.getByRole('status')).toContainText('of 34 searched');
});
